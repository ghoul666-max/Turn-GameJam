using Turn.View;
int checks = 0;
void Check(bool ok, string why) { checks++; if (!ok) throw new Exception(why); }
bool Near(float a, float b) => Math.Abs(a-b)<.0001f;
var s = new MobilePointerState();
Check(s.BeginStick(4), "first finger owns stick");
Check(!s.BeginStick(5), "second finger cannot steal stick");
Check(!s.DragStick(5,1,0,.15f), "foreign drag ignored");
Check(s.DragStick(4,3,4,.15f), "owner drag accepted");
Check(Near(s.X,.6f)&&Near(s.Y,.8f), "direction normalized outside radius");
Check(s.BeginRoll(5,true), "simultaneous roll finger accepted");
Check(Near(s.X,.6f)&&Near(s.Y,.8f), "roll preserves held movement");
Check(s.ConsumeRoll(), "roll pulse emitted");
Check(!s.ConsumeRoll(), "pulse only consumed once");
Check(!s.BeginRoll(5,true)&&!s.ConsumeRoll(), "held finger never repeats");
s.EndRoll(6);
Check(!s.BeginRoll(6,true), "foreign release doesn't release roll");
s.EndRoll(5);
Check(!s.BeginRoll(6,false)&&!s.ConsumeRoll(), "cooldown tap not queued");
Check(!s.BeginRoll(6,true)&&!s.ConsumeRoll(), "held cooldown tap cannot auto repeat when ready");
s.EndRoll(6);
Check(s.BeginRoll(6,true)&&s.ConsumeRoll(), "new tap ready queues once");
Check(!s.EndStick(6)&&Near(s.X,.6f), "roll finger release doesn't clear joystick");
s.DragStick(4,.1f,0,.15f);
Check(s.X==0&&s.Y==0,"deadzone zeros movement");
s.DragStick(4,.575f,0,.15f);
Check(Near(s.X,.5f),"deadzone remapped smoothly");
s.Reset();
Check(s.X==0&&s.Y==0&&!s.ConsumeRoll(),"modal/focus reset clears all requests");
Check(!s.DragStick(4,1,0,0)&&s.X==0,"old held drag cannot resume after reset");
Check(s.BeginStick(-1),"editor mouse negative ID supported");
Check(s.DragStick(-1,0,1,0)&&s.Y==1,"mouse drag supported");
Check(s.EndStick(-1)&&s.X==0&&s.Y==0,"owner release clears movement");
Console.WriteLine($"Mobile input checks passed ({checks} assertions).");
